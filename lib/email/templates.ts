/**
 * The frame every message shares.
 *
 * ⚠️ No `appUrl` parameter. It existed only to build an absolute URL for the
 * header image; the image is attached now, so there is nothing left for a
 * caller to get wrong.
 */
function shell(body: string, preheader: string): string {
  return `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${APP_NAME}</title></head>
<body style="margin:0;padding:0;background:${PAGE};-webkit-font-smoothing:antialiased;">
  <!-- The inbox preview line. Hidden in the body, but it is the first thing
       anybody reads, so it says something useful rather than repeating the
       subject. The zero-width run after it stops Gmail pulling the opening
       sentence in behind it. -->
  <div style="display:none;max-height:0;overflow:hidden;opacity:0;">${preheader}</div>
  <div style="display:none;max-height:0;overflow:hidden;">&#8203;&#8203;&#8203;&#8203;&#8203;&#8203;&#8203;&#8203;&#8203;&#8203;</div>

  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="background:${PAGE};padding:32px 12px;">
    <tr><td align="center">
      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width:620px;background:#ffffff;border:1px solid ${BORDER};border-radius:10px;overflow:hidden;">

        <!-- ── THE HEADER BAND ────────────────────────────────────────────────
             ⚠️ THE MARK IS AN IMAGE WITH REAL TEXT BESIDE IT, NOT INSTEAD OF
             IT. The image is attached rather than remote so it is not blocked
             the way a tracking pixel is — but a client can still fail to render
             it, and the product name must never depend on a picture. The
             wordmark is text; the mark is the flourish.
             ⚠️ NO BACKTICKS IN THIS COMMENT. It sits inside a JS template
             literal, so one would end the string and the file would stop
             parsing — which is exactly what happened when this was written.
             The alt is empty because the name is spelled out beside it; a
             screen reader announcing "Taskly logo Taskly" is noise. -->
        <tr><td bgcolor="${BAND}" style="background:${BAND};padding:22px 34px;">
          <table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr>
            <td style="padding-right:14px;vertical-align:middle;">
              <img src="cid:${MARK_CID}" width="${MARK_WIDTH}" height="${MARK_HEIGHT}" alt=""
                   style="display:block;width:${MARK_WIDTH}px;height:${MARK_HEIGHT}px;border:0;outline:none;text-decoration:none;" />
            </td>
            <td style="vertical-align:middle;">
              <div style="font:700 27px/1.05 ${SANS};color:${BAND_HEADING};letter-spacing:-.02em;">${APP_NAME}</div>
              <div style="margin-top:5px;font:400 12px/1.2 ${SANS};color:${BAND_MUTED};letter-spacing:.13em;text-transform:uppercase;">${DIVISION_NAME}</div>
            </td>
          </tr></table>
        </td></tr>

        <!-- The gold rule, full bleed. -->
        <tr><td bgcolor="${GOLD}" style="background:${GOLD};height:3px;line-height:3px;font-size:0;">&nbsp;</td></tr>
        <!-- …and the tab hanging off it. A row of its own rather than a
             negative margin, which email clients do not honour. -->
        <tr><td align="center" style="font-size:0;line-height:0;">${img(NOTCH)}</td></tr>

        <tr><td style="padding:26px 46px 34px 46px;font:400 15px/1.62 ${SANS};color:${BODY};">
          ${body}
        </td></tr>

        <!-- The footer band sits INSIDE the card, per the reference design. -->
        <tr><td bgcolor="${FOOT_BG}" style="background:${FOOT_BG};padding:18px 46px;border-top:1px solid ${BORDER};">
          <table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr>
            <td style="padding-right:12px;vertical-align:middle;">${img(MAIL)}</td>
            <td style="vertical-align:middle;font:400 12px/1.5 ${SANS};color:${MUTED};">
              If you were not expecting this, you may safely ignore this email.
            </td>
          </tr></table>
        </td></tr>
      </table>

      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="max-width:620px;">
        <tr><td align="center" style="padding:16px 8px 0 8px;font:400 11px/1.5 ${SANS};color:${MUTED};">
          ${ORGANISATION_NAME} &middot; ${DIVISION_NAME}
        </td></tr>
      </table>
    </td></tr>
  </table>
</body></html>`;
}

