/* ============================================================================
 * EMAIL TEMPLATES
 * ----------------------------------------------------------------------------
 * ── BUILT TO THE OWNER'S REFERENCE DESIGN, 2026-08-24 ────────────────────────
 * *"I want the exact icon, the size of the logo, and each and every thing you
 * can see. I want this same email template."*
 *
 * So this is a reconstruction of a supplied design rather than a set of choices
 * made here. Its structure, in order: a dark header band carrying the mark and
 * the wordmark; a gold rule with a small tab hanging off it; a ringed icon
 * badge; a centred headline over a short gold divider; the body; a gold-tinted
 * role chip; the action; a security note; a shield-centred divider; the
 * paste-this-instead link; and a pale footer band inside the card.
 *
 * ── EVERY ICON IS AN ATTACHED PNG, AND THAT IS NOT A SHORTCUT ────────────────
 * Gmail strips <svg> outright, so the lucide icons the application uses cannot
 * travel into a message. Emoji render as a different picture in every client.
 * So each glyph is a PNG generated by scripts/make-email-icons.mjs, attached to
 * the message and referenced with `cid:` — which needs no network fetch and is
 * therefore immune to the image blocking every major client does by default.
 * See ./icons.ts. Each template declares only the icons it actually uses, so a
 * password-reset message does not carry the invitation's badge.
 *
 * ── ALWAYS THE LIGHT PALETTE, NEVER THE DARK ONE (FR-215) ────────────────────
 * The application has a dark theme. Email does not get one. Dark-mode handling
 * in mail clients ranges from good to actively destructive — Outlook inverts
 * some colours and not others, several ignore `prefers-color-scheme`, and a few
 * rewrite backgrounds while leaving text alone. Unreadable in a way you cannot
 * test for. The dark header band is not an exception: it is painted explicitly
 * with BOTH a `bgcolor` attribute and a CSS background, which is how a colour
 * survives a client that strips one or the other.
 *
 * ── INLINE STYLES, TABLES, NO CSS VARIABLES ──────────────────────────────────
 * Everything the app does properly, email must do the 2005 way. `var()` is
 * unsupported in most clients, flexbox is unreliable, and `border-radius` is
 * ignored by Outlook's Word renderer — which is why the badge and the notch are
 * images rather than styled boxes. The hex values below are the only place in
 * this codebase where BR-025 is deliberately broken, because a token cannot
 * survive the journey into somebody's inbox.
 *
 * ── EVERY TEMPLATE RETURNS TEXT AS WELL ──────────────────────────────────────
 * Not politeness. A message with no plain-text alternative scores worse with
 * spam filters, and ADR-007's recovery design assumes these arrive.
 * ========================================================================= */

/* ── THE PALETTE ──────────────────────────────────────────────────────────────
   Read off the reference design and reconciled with styles/tokens.css, which is
   why each constant names its token where one exists.

   ⚠️ GOLD IS NOT A TEXT COLOUR ON WHITE — tokens.css measures gold-500 on white
   at 2.1:1. So gold appears here ONLY as a rule, a border, a chip background and
   an icon stroke; no text anywhere below is set in it. The one gold that is safe
   on light is gold-800 (5.4:1), and it lives in scripts/make-email-icons.mjs as
   the stroke colour for the glyphs that sit on the tinted panels. */
const BAND = '#0e2a2c'; /* ⚠️ must match BAND in scripts/make-email-mark.mjs */
const BAND_HEADING = '#ffffff';
const BAND_MUTED = '#9fb6b8';
const BRAND = '#0e5c63'; /* --teal-700, core brand teal */
const BRAND_DEEP = '#0a4046'; /* --teal-800 */
const GOLD = '#d4a63c'; /* --gold-500 */
const CHIP_BG = '#f8edd9'; /* --gold-100 */
const CHIP_EDGE = '#f2ddb4'; /* --gold-200 */
const INK = '#12222a'; /* --text-primary */
const BODY = '#3f5157';
const MUTED = '#5b6f77'; /* --text-secondary */
const BORDER = '#dde7e8'; /* --neutral-200 */
const HAIRLINE = '#e6eded';
const PANEL = '#f4f8f8'; /* --neutral-50 */
const PAGE = '#eef3f3';
const FOOT_BG = '#eef3f3';
const LINK = '#1155cc'; /* what a mail client renders a link as anyway */

const SANS = '-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,Helvetica,Arial,sans-serif';
const MONO = 'ui-monospace,SFMono-Regular,Menlo,Consolas,monospace';

export interface EmailAttachment {
  readonly filename: string;
  readonly content: string;
  readonly contentId: string;
  readonly contentType: string;
}

export interface Email {
  readonly subject: string;
  readonly html: string;
  readonly text: string;
  /** Inline images, by content id. Never empty — the mark is on every message. */
  readonly attachments: readonly EmailAttachment[];
}

/* --------------------------------------------------------------------------
 * Attachments
 * ------------------------------------------------------------------------ */

const MARK_ATTACHMENT: EmailAttachment = {
  filename: MARK_FILENAME,
  content: MARK_BASE64,
  contentId: MARK_CID,
  contentType: 'image/png',
};

const asAttachment = (icon: EmailIcon): EmailAttachment => ({
  filename: icon.filename,
  content: icon.base64,
  contentId: icon.cid,
  contentType: 'image/png',
});

/** The mark and the notch are on every message; the rest are per-template. */
const attach = (...icons: EmailIcon[]): EmailAttachment[] => [
  MARK_ATTACHMENT,
  asAttachment(NOTCH),
  ...icons.map(asAttachment),
];

const img = (icon: EmailIcon, alt = ''): string =>
  `<img src="cid:${icon.cid}" width="${icon.width}" height="${icon.height}" alt="${alt}"
        style="display:block;width:${icon.width}px;height:${icon.height}px;border:0;outline:none;text-decoration:none;" />`;

