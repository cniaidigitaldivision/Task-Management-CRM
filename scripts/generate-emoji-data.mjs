#!/usr/bin/env node
/* ============================================================================
 * GENERATE THE EMOJI PICKER'S DATA
 * ----------------------------------------------------------------------------
 *     node scripts/generate-emoji-data.mjs
 *
 * Owner, 2026-09-17: *"there is also a plus sign where I can add more emojis…
 * get all the emojis."* The full Unicode set (unicode-emoji-json) with search
 * words (emojilib), written to one compact generated module the picker loads
 * only when it is first opened.
 *
 * ⚠️ CAPPED AT EMOJI 15.0. Windows' Segoe UI Emoji does not draw the newest
 * emoji yet; offering them would put empty boxes in the picker — and send the
 * client a box. The cap moves up when the fonts do.
 * ========================================================================= */
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const groups = require('unicode-emoji-json/data-by-group.json');
const keywords = require('emojilib');

const MAX_VERSION = 15.0;
const LABEL = {
  smileys_emotion: 'Smileys',
  people_body: 'People',
  animals_nature: 'Nature',
  food_drink: 'Food',
  travel_places: 'Travel',
  activities: 'Activities',
  objects: 'Objects',
  symbols: 'Symbols',
  flags: 'Flags',
};

let count = 0;
const out = groups
  .filter((g) => g.slug !== 'component')
  .map((g) => ({
    key: g.slug,
    label: LABEL[g.slug] ?? g.name,
    emojis: g.emojis
      .filter((e) => Number(e.emoji_version) <= MAX_VERSION)
      .map((e) => {
        count += 1;
        const words = new Set([
          ...e.name.toLowerCase().split(/[\s:_,-]+/),
          ...(keywords[e.emoji] ?? []).map((k) => k.toLowerCase().replace(/_/g, ' ')),
        ]);
        words.delete('');
        /* [emoji, search words] — the smallest shape that still searches well. */
        return [e.emoji, [...words].join(' ')];
      }),
  }));

const body = `/* ⚠️ GENERATED by scripts/generate-emoji-data.mjs — do not edit by hand. */
/* ${count} emoji, Unicode emoji ≤ ${MAX_VERSION}, grouped as WhatsApp groups them. */

export interface EmojiGroup {
  readonly key: string;
  readonly label: string;
  /** [emoji, space-separated search words] */
  readonly emojis: ReadonlyArray<readonly [string, string]>;
}

export const EMOJI_GROUPS: readonly EmojiGroup[] = ${JSON.stringify(out)};
`;
fs.writeFileSync('components/crm/whatsapp/emoji-data.ts', body);
console.log(`${count} emoji in ${out.length} groups · ${Math.round(body.length / 1024)} KB`);
